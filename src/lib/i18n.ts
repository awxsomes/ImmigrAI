const DICTS: Record<UiLang, Partial<Dict>> = { en, es, zh, vi };

export function getDict(lang: string): Dict {
  const l = (UI_LANGS.includes(lang as UiLang) ? lang : "en") as UiLang;
  if (l === "en") return { ...en, ...strings };
  return { ...en, ...strings, ...DICTS[l], ...TRANSLATIONS[l]?.strings } as Dict;
}

export function isUiLang(lang: string): lang is UiLang {
  return UI_LANGS.includes(lang as UiLang);
}

